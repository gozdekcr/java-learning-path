package day06;

public class ForLoopExercises {
    public static void main(String[] args) {

        //FOR LOOP
        // for(initialization ; condition ; update) 


        //BASIC FOR LOOP
        System.out.println("Basic for loop");
        for (int i = 0 ; i<=5 ; i++) {
            System.out.print(i + " ");
            
        }

        System.out.println(); // new line

        //COUNTING BACKWARDS
        System.out.println("Counting backwards");
        for(int a = 10 ; a>=0 ; a--) {
            System.out.print(a + " ");
        }

        System.out.println(); // new line

        //ONLY EVEN NUMBERS
        System.out.println("Only even numbers");
        for(int g = 0 ; g<=20 ; g+=2) {
            System.out.print(g + " ");
        }






    }
    
}
