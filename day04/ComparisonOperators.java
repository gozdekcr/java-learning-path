package day04;

public class ComparisonOperators {
    public static void main(String[] args) {
        int a = 2;
        int b = 7;
        int c = 2;
        boolean result = a==b;

        System.out.println(a == b);
        System.out.println(result);

        System.out.println(a != b);

        System.out.println(a >= b);
        System.out.println(a <= c);
        System.out.println(a != c);




    }
}
