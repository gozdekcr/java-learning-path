package day01;

public class ComparisonOperators {
    public static void main(String[] args){
        int variableInt = 280605;
        System.out.println(variableInt);

        long variableLong = 100000000;
        System.out.println(variableLong);

        float num1 = 28.0f;
        float num2 = 28;
        System.out.println(num1);
        System.out.println(num2);

        double num3 = 3;
        double num4 = 5.45;
        System.out.println(num3);
        System.out.println(num4);

        char ch1 = 117;
        System.out.println(ch1);   //write ascii code for 117
        char ch2 = 'u';            //you can't use "" here
        System.out.println(ch2);

        boolean a = true;
        boolean b = false;
        System.out.println(a);
        System.out.println(b);

        String str1 = "Gozde";
        System.out.println(str1);

        int num10 = 5;
        int num11 = 7;

        boolean result = (num10 == num11);
        System.out.println(result);

        boolean result2 = (num10 <= num11);
        System.out.println(result2);



    }
    
}
